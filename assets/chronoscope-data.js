  function checkRedline(text) {
    if (!text || typeof text !== 'string') return { pass: true };
    for (let pattern of REDLINE_PATTERNS) {
      if (pattern.test(text)) {
        return {
          pass: false,
          reason: "时空邮局提示：留言包含敏感、消极或不符合社区规范的词汇。记忆长河只留存温暖、真实的生活印记与时代回响哦～"
        };
      }
    }
    return { pass: true };
  }

  function extractTags(year, text, eventCode) {
    const tags = [];
    const dbItem = YEAR_DATABASE[year] || YEAR_DATABASE[1998];
    
    // 1. 年代主标签
    tags.push(`#${year}${dbItem.tag}`);
    
    // 2. 公共事件编号
    tags.push(`#${eventCode || dbItem.eventCode}`);
    
    // 3. 用户文本实体与关键词提取
    if (text) {
      for (let entity of ENTITY_DICTIONARY) {
        if (text.includes(entity)) {
          tags.push(`#${entity}`);
        }
        if (tags.length >= 6) break;
      }
    }

    // 默认补充标签
    if (tags.length < 3) {
      tags.push("#时代记忆");
      tags.push("#时光信物");
    }

    return Array.from(new Set(tags));
  }

  function getSpacetimeWall() {
    try {
      const stored = localStorage.getItem("shide_spacetime_wall");
      if (stored) {
        return JSON.parse(stored);
      }
    } catch(e) {}
    return SEED_WALL_POSTS;
  }

  function saveSpacetimeWall(posts) {
    try {
      localStorage.setItem("shide_spacetime_wall", JSON.stringify(posts));
    } catch(e) {}
  }

